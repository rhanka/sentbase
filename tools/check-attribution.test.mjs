import assert from 'node:assert/strict';
import { test, after } from 'node:test';
import { mkdtempSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { spawnSync, execFileSync } from 'node:child_process';

const script = resolve('tools/check-attribution.sh');
const cwd = mkdtempSync(join(tmpdir(), 'attribution-test-'));
after(() => rmSync(cwd, { recursive: true, force: true }));
const env = { ...process.env, HOME: cwd, GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: '/dev/null',
  GIT_AUTHOR_NAME: 'Human Author', GIT_AUTHOR_EMAIL: 'author@example.org',
  GIT_COMMITTER_NAME: 'Human Committer', GIT_COMMITTER_EMAIL: 'committer@example.org' };
for (const key of ['GIT_DIR', 'GIT_WORK_TREE', 'GIT_INDEX_FILE', 'GIT_CONFIG_COUNT']) delete env[key];
const git = (args, extra = {}) => execFileSync('git', args, { cwd, env: { ...env, ...extra }, encoding: 'utf8' }).trim();
git(['init', '-q']);
const tree = git(['mktree']);
const run = (args, input = '', extra = {}) => spawnSync('sh', [script, ...args], {
  cwd, input, env: { ...env, ...extra }, encoding: 'utf8',
});
const hook = (message, extra) => run(['--message-file', '-'], message, extra);
function rejected(result) {
  assert.notEqual(result.status, 0, result.stdout + result.stderr);
  assert.doesNotMatch(result.stdout, /attribution-guard: OK/);
}

test('should allow normal AI feature discussion and human trailers', () => {
  for (const message of ['feat: add an OpenAI API option', 'fix: parse Claude model names',
    'feat: expose Gemini in the UI', 'Co-Authored-By: Alice <alice@example.org>']) {
    assert.equal(hook(message).status, 0, message);
  }
});

test('should reject agent markers, markdown forms and attribution trailers', () => {
  const agents = ['Claude', 'Anthropic', 'OpenAI Codex', 'ChatGPT', 'Codex', 'Copilot', 'Gemini',
    'Cursor', 'Mistral', 'Vibe', 'Muse', 'Devin', 'Aider', 'Windsurf', 'Codeium', 'Cline',
    'Roo', 'Jules', 'Junie', 'Amp', 'Antigravity', 'Sonnet', 'Opus', 'Haiku', 'o3-mini'];
  for (const agent of agents) {
    for (const message of [`Generated with ${agent}`, `Generated by [${agent}](https://example.org)`,
      `**Generated with** \`${agent}\``, `  Co-Authored-By: ${agent} <user@example.org>`,
      `> Assisted-by: ${agent}`, `Reviewed-by: ${agent}`, `Suggested-by: ${agent}`]) {
      rejected(hook(message));
    }
  }
  for (const message of ['Claude-Session: 550e8400-e29b', 'Claude-Session:', '🤖']) rejected(hook(message));
});

test('should reject either effective identity including GitHub bot email variants', () => {
  for (const role of ['AUTHOR', 'COMMITTER']) {
    for (const name of ['Claude Code', 'GitHub Copilot', 'OpenAI', 'ChatGPT', 'Codex',
      'Gemini', 'Cursor Agent', 'Mistral', 'Vibe', 'Muse', 'Devin', 'Aider']) {
      rejected(hook('fix: valid message', { [`GIT_${role}_NAME`]: name }));
    }
    for (const email of ['123+claude[bot]@users.noreply.github.com',
      'copilot-swe-agent[bot]@users.noreply.github.com', 'gemini-code-assist[bot]@users.noreply.github.com',
      '199175422+chatgpt-codex-connector[bot]@users.noreply.github.com',
      'cursoragent@cursor.com', 'noreply@anthropic.com', 'unknown[bot]@example.org',
      '49699333+dependabot[bot]@users.noreply.github.com']) {
      rejected(hook('fix: valid message', { [`GIT_${role}_EMAIL`]: email }));
    }
  }
});

test('should use git configuration when environment identities are absent', () => {
  git(['config', 'user.name', 'Claude Code']);
  git(['config', 'user.email', 'user@example.org']);
  rejected(hook('fix: valid message', { GIT_AUTHOR_NAME: undefined, GIT_AUTHOR_EMAIL: undefined }));
  assert.equal(hook('fix: valid message').status, 0); // effective human overrides win
});

test('should reject attributed objects in history including author and committer separately', () => {
  for (const extra of [{ GIT_AUTHOR_NAME: 'Claude' }, { GIT_COMMITTER_EMAIL: 'copilot[bot]@example.org' }]) {
    const commit = git(['commit-tree', tree, '-m', 'fix: valid message'], extra);
    rejected(run([commit]));
  }
  const bad = git(['commit-tree', tree, '-m', 'Generated with ChatGPT']);
  rejected(run([bad]));
  const clean = git(['commit-tree', tree, '-m', 'feat: add an AI feature']);
  assert.equal(run([clean]).status, 0);
});

test('should fail closed on invalid refs, unreadable files, git and grep errors', () => {
  rejected(run(['no-such-ref']));
  rejected(run(['--message-file', join(cwd, 'missing')]));
  rejected(run(['--message-file', cwd]));
  const bin = join(cwd, 'bin');
  mkdirSync(bin);
  const originalGit = execFileSync('which', ['git'], { encoding: 'utf8' }).trim();
  writeFileSync(join(bin, 'git'), '#!/bin/sh\ncase "$1" in show|var) exit 73;; esac\nexec "' + originalGit + '" "$@"\n', { mode: 0o755 });
  const extra = { PATH: `${bin}:${env.PATH}` };
  rejected(hook('fix: valid message', extra));
  const clean = git(['commit-tree', tree, '-m', 'fix: valid message']);
  rejected(run([clean], '', extra));
  writeFileSync(join(bin, 'grep'), '#!/bin/sh\nexit 2\n', { mode: 0o755 });
  rejected(hook('fix: valid message', extra));
});
